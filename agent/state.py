from typing import List, Dict, Any, Optional
from typing_extensions import TypedDict


class AgentState(TypedDict, total=False):
    """
    Canonical state schema for the LangGraph / NativeStateGraph orchestration loop.

    Fields
    ------
    user_input      : Raw natural-language goal provided by the user.
    task_id         : Unique identifier for this execution task (UUID-8).
    user_id         : Identifier for the active user session.
    intent          : ML-classified intent label (e.g. 'multi_step_task').
    intent_confidence : Confidence score [0.0–1.0] from the ML classifier.
    current_plan    : Ordered list of sub-task descriptions for this goal.
    current_step    : Zero-based index of the plan step currently executing.
    tool_selected   : Name of the tool chosen for the current step.
    tool_input      : Keyword arguments dict passed to the selected tool.
    tool_output     : Serialised ToolResult dict returned after execution.
    task_status     : Lifecycle status string (see below).
    retry_count     : Number of consecutive retries attempted for the current step.
    max_retries     : Maximum allowed retries before marking task FAILED.
    requires_approval : True when the selected tool is a sensitive action.
    approved_by_user  : None = not yet decided, True = approved, False = rejected.
    memory_context  : List of relevant memory strings retrieved at goal-understanding time.
    execution_trace : Ordered list of trace-event dicts for UI timeline rendering.
    final_response  : Human-readable final report generated by the finalize node.
    error_message   : Description of the last unrecoverable error, if any.

    task_status values
    ------------------
    "IN_PROGRESS"       – Normal execution in progress.
    "AWAITING_APPROVAL" – Paused at the human-approval gate.
    "APPROVED"          – Approval granted; resuming execution.
    "REJECTED"          – Approval denied by user.
    "CANCELLED"         – Cancelled during approval gate.
    "COMPLETED"         – All steps finished successfully.
    "FAILED"            – Exceeded max retries or unrecoverable error.
    """

    user_input: str
    task_id: str
    user_id: str
    intent: str
    intent_confidence: float
    current_plan: List[str]
    current_step: int
    tool_selected: Optional[str]
    tool_input: Optional[Dict[str, Any]]
    tool_output: Optional[Dict[str, Any]]
    task_status: str
    retry_count: int
    max_retries: int
    requires_approval: bool
    approved_by_user: Optional[bool]
    memory_context: List[str]
    execution_trace: List[Dict[str, Any]]
    final_response: str
    error_message: Optional[str]
